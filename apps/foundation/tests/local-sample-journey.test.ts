import {expect,it,vi} from 'vitest';
import {LocalReferenceStore} from '../src/media/local-reference.ts';
import {LocalWardrobe} from '../src/media/local-wardrobe.ts';
import {LocalSavedLooks,SAMPLE_LOOKS} from '../src/looks/local-saved-looks.ts';
import {LocalShoppingList} from '../src/shopping/local-shopping-list.ts';
import {LocalPrivacy} from '../src/privacy/local-privacy.ts';
import {createNotebookPreview,NotebookPreviewController,PREVIEW_OWNER} from '../src/session/notebook-preview.ts';
import {LocalLookFeedback,sampleShoeReplacement} from '../src/feedback/local-look-feedback.ts';
function fixture(){
 let serial=0;const ports={createURL:()=>`blob:fixture_${++serial}`,revokeURL:vi.fn()};
 const reference=new LocalReferenceStore({...ports,normalize:async()=>new Blob(['pixels'],{type:'image/webp'})});
 const wardrobe=new LocalWardrobe(ports),looks=new LocalSavedLooks(),shopping=new LocalShoppingList(),privacy=new LocalPrivacy();
 const controller=new NotebookPreviewController(createNotebookPreview(()=>0)),feedback=new LocalLookFeedback();
 privacy.bind('session',{read:()=>({data:{notes:controller.session.snapshot(PREVIEW_OWNER)!.notes},photos:reference.exportPhotos().map(p=>({id:'session_'+p.id,blob:p.blob}))}),clear:()=>{controller.clear();reference.clear();wardrobe.clearSelection();feedback.clear();}});
 privacy.bind('wardrobe',{read:()=>({data:{items:wardrobe.exportItems().map(p=>({id:p.id,description:p.description}))},photos:wardrobe.exportItems().map(p=>({id:'wardrobe_'+p.id,blob:p.blob}))}),clear:()=>wardrobe.clear()});
 privacy.bind('looks',{read:()=>({data:{looks:looks.snapshot().looks},photos:[]}),clear:()=>looks.clear()});
 privacy.bind('shopping',{read:()=>({data:{entries:shopping.snapshot().entries},photos:[]}),clear:()=>shopping.clear()});
 for(const model of [wardrobe,looks,shopping,reference])model.subscribe(()=>privacy.invalidate());
 return{reference,wardrobe,looks,shopping,privacy,controller,feedback};
}
it('composed local sample journey preserves explicit saves, revisions, export scope and clearing',async()=>{
 const s=fixture(),c=s.controller;
 c.propose(c.session.ticket(PREVIEW_OWNER)!,'occasion','Outdoor wedding');c.confirm('occasion');
 c.propose(c.session.ticket(PREVIEW_OWNER)!,'season','November; season not specified');
 c.save(c.beginEdit('budget')!,'USD 350 maximum (items only)');
 await s.reference.choose([new Blob(['generated fixture'],{type:'image/png'})]);s.reference.confirm('Synthetic red jacket','owned');
 expect(s.wardrobe.snapshot().items).toEqual([]);expect(s.wardrobe.save(s.reference.exportOwned())).toBe(true);
 expect(s.reference.snapshot().message).toBe('Reference confirmed for this session. Saving to Wardrobe is a separate action.');
 s.wardrobe.select(1,true);s.feedback.open();
 s.feedback.add({kind:'keep',target:{kind:'item',itemId:'dress'},text:'Keep the dress',origin:'touch'});
 expect(s.feedback.completeChange(s.feedback.beginChange('shoes')!,sampleShoeReplacement(1))).toBe(true);
 expect(s.feedback.snapshot().keptIds).toContain('dress');expect(s.feedback.snapshot().releaseEnabled).toBe(false);
 s.looks.save(SAMPLE_LOOKS[0]);expect(s.shopping.snapshot().entries).toEqual([]);
 expect(s.shopping.addPiece('sample_emerald','jacket')).toBe(false);s.shopping.addPiece('sample_emerald','dress');
 s.shopping.simulateAvailability('sample_emerald:dress',false);expect(s.shopping.snapshot().subtotalCents).toBeNull();
 s.shopping.simulateAvailability('sample_emerald:dress',true);expect(s.shopping.snapshot().subtotalCents).toBeNull();
 s.shopping.recheck('sample_emerald:dress');expect(s.shopping.snapshot().subtotalCents).toBe(14000);
 expect(await s.privacy.prepare(['session','wardrobe','looks','shopping'])).toBe(true);
 const ready=s.privacy.snapshot().ready!,out=JSON.parse(ready.json);
 expect(Object.keys(out.categories)).toEqual(['session','wardrobe','looks','shopping']);
 expect(out.categories.wardrobe.photos).toHaveLength(1);expect(out.categories.session.photos).toHaveLength(1);
 expect(out.categories.looks.data).not.toHaveProperty('notes');expect(ready.json).not.toContain('blob:');
 s.privacy.cancel();expect(s.privacy.snapshot().ready).toBeNull();expect(s.wardrobe.snapshot().items).toHaveLength(1);
 const late=c.session.ticket(PREVIEW_OWNER)!;expect(s.privacy.clear(['session'])).toBe(true);
 expect(c.propose(late,'season','Late old text')).toBe('stale');expect(s.reference.snapshot().reference).toBeNull();
 expect(s.wardrobe.snapshot().items).toHaveLength(1);expect(s.wardrobe.snapshot().selected).toEqual([]);
 expect(s.looks.snapshot().looks).toHaveLength(1);expect(s.shopping.snapshot().entries).toHaveLength(1);
 c.end();const next=createNotebookPreview(()=>0,{budget:'USD 350 maximum (items only)'});
 expect(next.snapshot(PREVIEW_OWNER)!.notes.budget.value).toBe('USD 350 maximum (items only)');expect(next.snapshot(PREVIEW_OWNER)!.notes.occasion.value).toBe('');
 expect(s.privacy.clear(['session','wardrobe','looks','shopping'])).toBe(true);
 expect(s.wardrobe.snapshot().items).toEqual([]);expect(s.looks.snapshot().looks).toEqual([]);expect(s.shopping.snapshot().entries).toEqual([]);
 const fresh=fixture();expect(fresh.reference.snapshot().reference).toBeNull();expect(fresh.controller.session.snapshot(PREVIEW_OWNER)!.notes.budget.value).toBe('');
});
it('late photo export cannot return after composed sample clearing',async()=>{
 const s=fixture();await s.reference.choose([new Blob(['fixture'])]);s.reference.confirm('jacket','owned');s.wardrobe.save(s.reference.exportOwned());
 let finish!:(value:string)=>void;const privacy=new LocalPrivacy(()=>new Promise(resolve=>{finish=resolve;}));
 privacy.bind('wardrobe',{read:()=>({data:s.wardrobe.snapshot().items,photos:s.wardrobe.exportItems().map(p=>({id:'photo_'+p.id,blob:p.blob}))}),clear:()=>s.wardrobe.clear()});
 const pending=privacy.prepare(['wardrobe']);expect(privacy.snapshot().busy).toBe(true);privacy.clear(['wardrobe']);finish('fixture');
 expect(await pending).toBe(false);expect(privacy.snapshot().ready).toBeNull();expect(s.wardrobe.snapshot().items).toEqual([]);
});
